
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using Godot;
using Godot.Bridge;

// Disables the .NET runtime's automatic P/Invoke marshalling (e.g. converting
// C# strings to C strings, pinning arrays, etc.). Godot.Bindings does its own
// low-level marshalling via unsafe pointers, and the runtime's version would
// conflict with it. Required for all GDExtension assemblies.
[assembly: DisableRuntimeMarshalling]

// allows us to set our own entry point name, must match the .gdextension file's entry_symbol
[assembly: DisableGodotEntryPointGeneration]

namespace MyProject;

public static class EntryPoint {

    // Set once GodotBridge has been initialized. NativeAOT libraries are never really unloaded,
    // so this survives the extension being unloaded and loaded again in the same process.
    private static bool _initialized;

    // Called once by Godot when the extension library is first loaded (before any scene runs).
    // Sets up GodotBridge and registers the initializer/terminator callbacks that Godot will
    // call at each InitializationLevel.
    //
    // HOT RELOAD
    //   When the editor reloads the extension (reloadable = true and the binary changed), Godot
    //   calls this again in the same process. GodotBridge can't be initialized twice, and the
    //   exception it throws can't cross back into Godot, so it would close the editor. Returning
    //   false instead makes Godot report that the reload failed: the extension's classes are
    //   missing until the editor restarts, but nothing crashes and unsaved work isn't lost.
    [UnmanagedCallersOnly(EntryPoint = "init")]
    public static bool Initialize(nint getProcAddress, nint library, nint initialization) {
        if (_initialized) {
            // GD.PrintErr isn't usable here, since the bridge isn't set up for this load
            System.Console.Error.WriteLine($"{typeof(EntryPoint).Namespace} GDExtension can't be reloaded while the editor is running; restart the editor to load the new build.");
            return false;
        }
        _initialized = true;

        GodotBridge.Initialize(getProcAddress, library, initialization, config => {
            config.SetMinimumLibraryInitializationLevel(InitializationLevel.Scene);
            config.RegisterInitializer(InitializeClasses);
            config.RegisterTerminator(DeinitializeClasses);
        });
        return true;
    }

    // Called by Godot once per InitializationLevel in ascending order: Core → Servers → Scene → Editor
    // (Editor only runs inside the editor, never in an exported game).
    //
    // CLASS REGISTRATION
    //   ClassDBExtensions.InitializeUserTypes() is generated by Godot.SourceGeneration at build
    //   time. It scans every [GodotClass] in this assembly and emits a RegisterClass call for
    //   each one. Adding [GodotClass] to a new type is all that's needed — no manual registration.
    //
    // INITIALIZATION LEVELS
    //   Godot.SourceGeneration always registers classes at InitializationLevel.Scene, which is
    //   correct for Node-derived types. If a class must be registered at a different level (e.g.
    //   Core for a pure data type, Servers for a type that needs the rendering server), register
    //   it manually and exclude it from auto-registration by NOT marking it [GodotClass]:
    //
    //     if (level == InitializationLevel.Core)
    //         GodotRegistry.RegisterClass<MyResource>(MyResource.BindMembers);
    //
    //   BindMembers is always generated by Godot.SourceGeneration for any [GodotClass] type —
    //   only the timing of when it is called differs.
    //
    // EDITOR PLUGINS
    //   Classes deriving from editor-only engine classes (EditorPlugin, EditorExportPlugin,
    //   EditorInspectorPlugin, EditorTranslationParserPlugin, ...) can only be registered at
    //   InitializationLevel.Editor, since Godot registers those base classes there. The generated
    //   InitializeUserTypes() registers every [GodotClass] at Scene, so once the extension has editor
    //   classes, stop calling it and register each class at its own level instead, the way
    //   godot-dotnet's own editor plugin does (git-submodules/godot-dotnet/src/Godot.EditorIntegration/Main.cs):
    //
    //     if (level == InitializationLevel.Scene)
    //         GodotRegistry.RegisterClass<ExampleNode>(ExampleNode.BindMembers);
    //
    //     if (level == InitializationLevel.Editor) {
    //         GodotRegistry.RegisterClass<MyEditorPlugin>(MyEditorPlugin.BindMembers);
    //         GodotRegistry.AddEditorPluginByType<MyEditorPlugin>();   // adds it to the editor, like enabling a plugin
    //     }
    //
    //   Mark editor classes [GodotClass(Tool = true)] so they run in the editor. Plugins added with
    //   AddEditorPluginByType are removed automatically when the extension unloads.
    //
    // OTHER USES
    //   - Instantiate and store extension-wide singletons
    //   - Open log files or connect to external services
    //   - Register custom ResourceFormatLoader/Saver types
    private static void InitializeClasses(InitializationLevel level) {
        GD.PrintS($"loading {typeof(EntryPoint).Namespace} GDExtension ({level})..");
        ClassDBExtensions.InitializeUserTypes(level);
    }

    // Called by Godot when the extension is unloaded — once per InitializationLevel,
    // in reverse order (Scene → Servers → Core). GodotBridge automatically calls
    // GodotRegistry.UnregisterAllClasses() after all terminator callbacks finish,
    // so class unregistration does not need to be done here.
    //
    // Use this method to tear down anything your InitializeClasses set up:
    //   - Release native handles or unmanaged resources
    //   - Flush or close log files
    //   - Disconnect from external services (sockets, databases, etc.)
    //   - Dispose of singletons that hold unmanaged state
    //
    // The level parameter mirrors what was passed to InitializeClasses, so you
    // can guard teardown to the same level where initialization happened:
    //   if (level != InitializationLevel.Scene) return;
    //
    // remember this won't be called at all if the editor or your game crashes!
    private static void DeinitializeClasses(InitializationLevel level) {
        GD.PrintS($"unloading {typeof(EntryPoint).Namespace} GDExtension ({level})..");
        ClassDBExtensions.DeinitializeUserTypes(level);
    }
}
